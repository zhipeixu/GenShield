"""
AIGI-Holmes Dataset for AI-Generated Image Detection (VLM Task).

Task: Given an image (AI-generated or real), determine if it's AI-generated
and provide detailed reasoning about the visual artifacts/anomalies.

This is a pure VLM task - only uses VIT encoding, no VAE, CE loss only.

Input: System prompt + Image (VIT) + Query
Output: Detection result + Detailed analysis (CE loss only)

JSONL format:
{
    "query": "Can you discern if this picture is made by AI or if it is real?...\n<image>",
    "response": "This is a fake image.\n\nImage Description: ...\n\nReasons: ...",
    "images": ["./dataset/xxx.png"]
}
"""

import json
import os
import traceback
from PIL import Image, ImageFile, PngImagePlugin

from ..data_utils import pil_img2rgb
from ..distributed_iterable_dataset import DistributedIterableDataset


Image.MAX_IMAGE_PIXELS = 200000000
ImageFile.LOAD_TRUNCATED_IMAGES = True
MaximumDecompressedSize = 1024
MegaByte = 2 ** 20
PngImagePlugin.MAX_TEXT_CHUNK = MaximumDecompressedSize * MegaByte


class AIGIDetectionIterableDataset(DistributedIterableDataset):
    """
    Dataset for AIGI-Holmes: AI-Generated Image Detection (VLM Task).
    
    This is a pure VLM task using only VIT encoding for image understanding.
    
    Training Flow:
    Input (no loss):
        - System prompt
        - Query text (before <image>)
        - Image (VIT encoding only)
        - Query text (after <image>)
    
    Output (CE loss only):
        - Detection result (real/fake) + detailed analysis
    """

    def __init__(
        self, 
        dataset_name, 
        transform,  # VIT image transform (from image_transform_args)
        tokenizer, 
        frame_sampler,  # For video support (from frame_sampler_args)
        jsonl_path_list, 
        data_dir_list,  # Base directory for relative image paths
        num_used_data,
        local_rank=0, 
        world_size=1, 
        num_workers=8, 
        data_status=None,
        shuffle_lines=False,
        shuffle_seed=0,
        system_prompt=None,
        **kwargs
    ):
        super().__init__(dataset_name, local_rank, world_size, num_workers)
        self.transform = transform
        self.tokenizer = tokenizer
        self.frame_sampler = frame_sampler
        self.data_status = data_status
        
        # Image base directory (for relative paths in JSONL)
        if data_dir_list and len(data_dir_list) > 0:
            self.image_base_dir = data_dir_list[0]
        else:
            self.image_base_dir = ""
        
        # System prompt for AI image detection task
        if system_prompt is None:
            self.system_prompt = (
                "You are an AI image detection assistant. "
                "This is a picture that is suspected to be generated by AI. "
                "Please observe this picture carefully to determine whether it was generated by AI "
                "and provide a basis for your judgment."
            )
        else:
            self.system_prompt = system_prompt
        
        self.data_paths = self.get_data_paths(
            jsonl_path_list, 
            data_dir_list,
            num_used_data, 
            shuffle_lines, 
            shuffle_seed,
        )
        self.set_epoch()

    def get_data_paths(
        self, 
        jsonl_path_list,
        data_dir_list, 
        num_used_data, 
        shuffle_lines, 
        shuffle_seed,
    ):
        """Load and optionally shuffle data from JSONL files."""
        data_paths = []
        for jsonl_path, image_dir, num_data_point in zip(
            jsonl_path_list, data_dir_list, num_used_data
        ):
            with open(jsonl_path, 'r', encoding='utf-8') as f:
                raw_data = f.readlines()
            
            if shuffle_lines:
                self.rng.seed(shuffle_seed)
                self.rng.shuffle(raw_data)
            
            raw_data = raw_data[:num_data_point]
            # Store both json data and image_dir for each sample
            data_paths.extend([(json_data, image_dir) for json_data in raw_data])
        
        return data_paths

    def _resolve_image_path(self, image_path, image_dir):
        """Resolve image path (handle relative paths)."""
        if os.path.isabs(image_path):
            return image_path
        # Remove leading ./ if present
        if image_path.startswith('./'):
            image_path = image_path[2:]
        if image_dir:
            return os.path.join(image_dir, image_path)
        return image_path

    def __iter__(self):
        """Iterate over the dataset."""
        data_paths_per_worker, worker_id = self.get_data_paths_per_worker()
        
        if self.data_status is not None:
            row_start_id = self.data_status[worker_id] + 1
        else:
            row_start_id = 0

        transform_stride = self.transform.stride

        print(
            f"rank-{self.local_rank} worker-{worker_id} dataset-{self.dataset_name}: "
            f"resuming data at row#{row_start_id}"
        )

        while True:
            data_paths_per_worker_ = data_paths_per_worker[row_start_id:]
            
            for row_idx, (data, image_dir) in enumerate(data_paths_per_worker_, start=row_start_id):
                num_tokens = 0
                image_tensor_list = []
                text_ids_list = []
                sequence_plan = []

                try:
                    data_item = json.loads(data)
                    
                    query = data_item['query']
                    response = data_item['response']
                    images = data_item.get('images', [])
                    
                    # Load images
                    raw_images = []
                    if images:
                        for img_path in images:
                            full_path = self._resolve_image_path(img_path, image_dir)
                            raw_images.append(pil_img2rgb(Image.open(full_path)))
                    
                    # Transform images
                    for raw_image in raw_images:
                        image_tensor = self.transform(raw_image, img_num=len(raw_images))
                        image_tensor_list.append(image_tensor)
                        height, width = image_tensor.shape[1:]
                        num_tokens += width * height // transform_stride ** 2

                    # Build sequence: system_prompt + query (with images) + response
                    # Add system prompt first (no loss)
                    system_text_ids = self.tokenizer.encode(self.system_prompt + "\n\n")
                    if len(system_text_ids) > 0:
                        text_ids_list.append(system_text_ids)
                        num_tokens += len(system_text_ids)
                        sequence_plan.append({
                            'type': 'text',
                            'enable_cfg': 0,
                            'loss': 0,
                            'special_token_loss': 0,
                            'special_token_label': None,
                        })

                    # Process query with <image> placeholders
                    num_images = len(image_tensor_list)
                    if '<image>' in query:
                        text_parts = query.split('<image>')
                        image_idx = 0
                        for idx, text_part in enumerate(text_parts):
                            # Add text part (no loss for input)
                            if text_part.strip():
                                text_ids = self.tokenizer.encode(text_part.strip())
                                if len(text_ids) > 0:
                                    text_ids_list.append(text_ids)
                                    num_tokens += len(text_ids)
                                    sequence_plan.append({
                                        'type': 'text',
                                        'enable_cfg': 0,
                                        'loss': 0,
                                        'special_token_loss': 0,
                                        'special_token_label': None,
                                    })
                            
                            # Add image placeholder (VIT only, no loss)
                            if idx < len(text_parts) - 1 and image_idx < num_images:
                                sequence_plan.append({
                                    'type': 'vit_image',
                                    'enable_cfg': 0,
                                    'loss': 0,
                                    'special_token_loss': 0,
                                    'special_token_label': None,
                                })
                                image_idx += 1
                    else:
                        # No <image> in query, add query text then all images
                        if query.strip():
                            text_ids = self.tokenizer.encode(query.strip())
                            if len(text_ids) > 0:
                                text_ids_list.append(text_ids)
                                num_tokens += len(text_ids)
                                sequence_plan.append({
                                    'type': 'text',
                                    'enable_cfg': 0,
                                    'loss': 0,
                                    'special_token_loss': 0,
                                    'special_token_label': None,
                                })
                        
                        # Add all images
                        for _ in range(num_images):
                            sequence_plan.append({
                                'type': 'vit_image',
                                'enable_cfg': 0,
                                'loss': 0,
                                'special_token_loss': 0,
                                'special_token_label': None,
                            })

                    # Add response (CE loss)
                    response_ids = self.tokenizer.encode(response)
                    if len(response_ids) > 0:
                        text_ids_list.append(response_ids)
                        num_tokens += len(response_ids)
                        sequence_plan.append({
                            'type': 'text',
                            'enable_cfg': 0,
                            'loss': 1,  # CE loss on response
                            'special_token_loss': 0,
                            'special_token_label': None,
                        })

                    # Validate that we have loss
                    has_loss = [item['loss'] for item in sequence_plan]
                    if sum(has_loss) == 0:
                        print(f'No loss defined, skipped.')
                        continue

                    yield dict(
                        image_tensor_list=image_tensor_list,
                        text_ids_list=text_ids_list,
                        sequence_plan=sequence_plan,
                        num_tokens=num_tokens,
                        data_indexes={
                            "data_indexes": row_idx,
                            "worker_id": worker_id,
                            "dataset_name": self.dataset_name,
                        }
                    )

                except Exception as e:
                    print(f"Error processing row {row_idx}: {e}")
                    traceback.print_exc()
                    continue

            # Repeat dataset
            row_start_id = 0
            print(f"{self.dataset_name} repeat in rank-{self.local_rank} worker-{worker_id}")
